"""Tests for `post --platform github --mode deep`: no dedup against an older summary, and a
summary that says what it counts and that it is a deep review.

Everything runs in-process against the recording stand-ins from test_github_review.py and
test_github_standdown.py, so no test touches the network.
"""

import os
import unittest
from unittest.mock import patch

from tests.helpers import commit, make_repo
from tests.test_github_review import (
    HEAD,
    OLD,
    FakeGitHub,
    comment,
    finding,
    marker,
    review,
    review_data,
    thread,
)
from tests.test_github_standdown import ActionsGitHub, StandDownTestCase

STANDARD_HEADING = "### Issues Found (2 total)"
DEEP_HEADING = "### Inline comments (2)"


class DeepPostTestCase(StandDownTestCase):
    def two_commit_repo(self):
        """A repository whose second commit changes only line 20; returns (first, second)."""
        base = "".join(f"line{i}\n" for i in range(1, 31))
        repo, _ = make_repo(self.tmp, {"x.py": base})
        first = commit(repo, {"x.py": base + "extra\n"})
        lines = [f"line{i}\n" for i in range(1, 31)] + ["extra\n"]
        lines[19] = "changed\n"
        second = commit(repo, {"x.py": "".join(lines)})
        self.addCleanup(os.chdir, os.getcwd())
        os.chdir(repo)
        return first, second

    def post_after_older_summary(self, mode):
        first, second = self.two_commit_repo()
        fake = ActionsGitHub(head=second)
        fake.comment_pages = [([comment(2, f"s\n\n{marker(first)}")], "")]
        fake.thread_pages = [
            (
                [
                    thread(101, path="x.py", line=10),
                    thread(102, path="x.py", line=10, outdated=True),
                    thread(103, path="x.py", line=5),
                ],
                False,
            )
        ]
        args = self.args(review_data([finding(line=10), finding(line=20, text="New bug")]))
        args.mode = mode
        code, out, _ = self.call(review._github_post, args, env=self.env(head=second), fake=fake)
        self.assertEqual(code, 0, out)
        return fake, second

    def deleted(self, fake):
        return [c[1].rsplit("/", 1)[-1] for c in fake.of("DELETE")]


class DeepDedupTests(DeepPostTestCase):
    def test_deep_post_after_an_older_summary_posts_findings_on_unchanged_lines(self):
        fake, second = self.post_after_older_summary("deep")
        self.assertEqual(self.deleted(fake), ["101", "102", "103"])
        self.assertEqual([p["line"] for p in fake.inline_payloads()], [10, 20])
        body = fake.summary_body()
        self.assertNotIn("Still open", body)
        self.assertTrue(body.endswith(marker(second)))

    def test_standard_post_after_an_older_summary_still_skips_unchanged_lines(self):
        fake, _ = self.post_after_older_summary("standard")
        self.assertEqual(self.deleted(fake), ["102", "103"])
        self.assertEqual([p["line"] for p in fake.inline_payloads()], [20])
        self.assertIn(
            "- Still open from earlier runs, on code that did not change: 1", (fake.summary_body())
        )

    def test_deep_post_never_runs_dedup(self):
        fake = ActionsGitHub()
        fake.comment_pages = [([comment(2, f"s\n\n{marker(OLD)}")], "")]
        fake.thread_pages = [([thread(101, line=10)], False)]
        args = self.args(review_data([finding(line=10)]))
        args.mode = "deep"
        with patch.object(
            review, "filter_already_reviewed", side_effect=AssertionError("dedup ran")
        ):
            code, _, _ = self.call(review._github_post, args, fake=fake)
        self.assertEqual(code, 0)
        self.assertEqual(self.deleted(fake), ["101"])
        self.assertEqual([p["line"] for p in fake.inline_payloads()], [10])


class DeepSummaryTests(DeepPostTestCase):
    def summary(self, mode, data=None, env=None):
        fake = ActionsGitHub()
        args = self.args(data or review_data([finding(line=5), finding(line=6, severity="minor")]))
        if mode is not None:
            args.mode = mode
        code, out, _ = self.call(review._github_post, args, env=env, fake=fake)
        self.assertEqual(code, 0, out)
        return fake.summary_body()

    def test_deep_summary_counts_inline_comments_and_names_the_mode(self):
        env = self.env(AGENT_MODEL="m", AGENT_REASONING_EFFORT="high")
        body = self.summary("deep", env=env)
        self.assertIn(f"\n{DEEP_HEADING}\n", body)
        self.assertNotIn("Issues Found", body)
        footer = [line for line in body.split("\n") if line.startswith("*Generated by")]
        self.assertEqual(len(footer), 1)
        self.assertTrue(
            footer[0].endswith(" • Harness: claude-code • Model: m • Effort: high • Mode: deep*"),
            footer[0],
        )

    def test_deep_summary_differs_from_standard_only_in_the_heading_and_footer(self):
        standard = self.summary("standard")
        deep = self.summary("deep")
        self.assertEqual(
            deep.replace(DEEP_HEADING, STANDARD_HEADING).replace(" • Mode: deep*", "*"), standard
        )

    def test_standard_summary_is_unchanged_by_mode(self):
        without_mode = FakeGitHub()
        args = self.args(review_data([finding(line=5), finding(line=6, severity="minor")]))
        self.call(review._github_post, args, fake=without_mode)
        standard = self.summary("standard")
        self.assertEqual(standard, without_mode.summary_body())
        self.assertIn(STANDARD_HEADING, standard)
        self.assertNotIn("Mode:", standard)

    def test_deep_summary_without_inline_comments_still_names_the_mode(self):
        body = self.summary("deep", data=review_data())
        self.assertNotIn("###", body.split("\n---\n")[0].split("\n", 1)[1])
        self.assertIn(" • Mode: deep*", body)

    def test_build_summary_body_defaults_to_the_standard_text(self):
        data = review_data([finding(line=5)])
        self.assertEqual(
            review._github_build_summary_body(data, marker(HEAD)),
            review._github_build_summary_body(data, marker(HEAD), mode="standard"),
        )


if __name__ == "__main__":
    unittest.main()
